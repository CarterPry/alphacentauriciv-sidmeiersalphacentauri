import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';

const output = new URL('../output/browser/', import.meta.url);
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [], checks = [];
page.on('pageerror', error => errors.push(String(error)));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
const base = process.env.TEST_URL || 'http://127.0.0.1:5173/library.html';
const textState = async () => JSON.parse(await page.evaluate(() => window.render_game_to_text()));
const record = name => checks.push({ name, passed: true });
try {
  await page.goto(base);
  await page.getByRole('heading', { name: /Welcome back/ }).waitFor();
  assert.equal(await page.locator('#start-btn').getAttribute('href'), '/play.html?edition=alien-crossfire');
  assert.equal(await page.locator('.stat').count(), 4);
  assert.equal(await page.evaluate(() => window.crossOriginIsolated), true);
  await page.screenshot({ path: new URL('landing.png', output).pathname, fullPage: true });
  record('Archive loads, both edition launch links exist, browser isolation enabled');

  await page.getByRole('link', { name: 'Research', exact: true }).click();
  await page.getByRole('heading', { name: 'The path to discovery' }).waitFor();
  assert.ok((await textState()).eligible.includes('Ecology'));
  await page.locator('#tech-search').fill('Industrial Base');
  await page.locator('.tech-row').click();
  await page.locator('#mark-known').click();
  assert.ok((await textState()).known.includes('Indust'));
  assert.ok(!(await textState()).eligible.includes('Chemist'));
  await page.locator('#tech-search').fill('Applied Physics');
  await page.locator('.tech-row').click();
  await page.locator('#mark-known').click();
  assert.ok((await textState()).eligible.includes('Chemist'));
  await page.locator('#tech-search').fill('High Energy Chemistry');
  await page.locator('.tech-row').click();
  assert.equal(await page.locator('.tech-detail .chip').textContent(), 'AVAILABLE');
  await page.screenshot({ path: new URL('research.png', output).pathname, fullPage: true });
  record('Two prerequisite discoveries unlock High Energy Chemistry in DOM and state');
  await page.locator('#mark-known').click();
  assert.ok(!(await textState()).eligible.includes('Chemist'));
  await page.locator('#clear-known').click();
  assert.equal((await textState()).known.length, 0);
  assert.equal(await page.locator('.tech-detail .chip').textContent(), 'LOCKED');
  await page.locator('#edition').selectOption('alpha');
  assert.equal((await textState()).edition, 'alpha');
  assert.ok(!(await textState()).eligible.includes('PrPsych'));
  record('Ownership suppresses already known research, reset and base-edition switch work');

  await page.getByRole('link', { name: 'Assets', exact: true }).click();
  await page.getByRole('heading', { name: 'The planetary archive' }).waitFor();
  await page.locator('#asset-search').fill('openinga.pcx');
  assert.ok(await page.locator('.asset-card').count() >= 2);
  await page.locator('[data-path="openinga.pcx"]').click();
  await page.locator('dialog[open] .asset-large').waitFor();
  assert.ok(await page.locator('.asset-large').evaluate(img => img.complete && img.naturalWidth > 0));
  assert.match(await page.locator('.asset-metadata').textContent(), /Source SHA-256: [0-9a-f]{64}/);
  await page.screenshot({ path: new URL('asset.png', output).pathname, fullPage: true });
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('dialog[open]').count(), 0);
  await page.locator('#asset-search').fill('');
  await page.locator('#next').click();
  assert.equal((await textState()).assetPage, 1);
  await page.locator('#asset-kind').selectOption('audio');
  assert.equal((await textState()).assetPage, 0);
  assert.equal((await textState()).assetResults, 508);
  await page.locator('.asset-card').first().click();
  await page.locator('audio').waitFor();
  await page.waitForFunction(() => document.querySelector('audio')?.readyState >= 1);
  await page.locator('.dialog-close').click();
  record('Image search, original artwork, hashes, Escape, pagination and audio metadata work');

  await page.getByRole('link', { name: 'Analysis', exact: true }).click();
  await page.getByRole('heading', { name: 'From evidence to a browser' }).waitFor();
  const links = await page.locator('main a[href^="/evidence/"]').evaluateAll(as => as.map(a => a.getAttribute('href')));
  for (const link of links) assert.equal((await page.request.get(new URL(link, base).href)).status(), 200, link);
  record('Every rendered evidence link returns a retained source record');

  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('link', { name: 'Play', exact: true }).click();
  await page.getByRole('heading', { name: /Welcome back/ }).waitFor();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: new URL('mobile.png', output).pathname, fullPage: true });
  record('Mobile launch layout fits viewport without horizontal overflow');
  assert.deepEqual(errors, []);
  await writeFile(new URL('results.json', output), JSON.stringify({ checks, errors, state: await textState() }, null, 2));
  console.log(`${checks.length} browser flows passed; screenshots in output/browser.`);
} finally { await browser.close(); }
